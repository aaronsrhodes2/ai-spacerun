"""
Coal line 1: the 343k-ton coal patch at (145,62) to the base, by train.

    track     starts at the patch (open end (145,72) heading north; first piece (144,70)),
              runs north 37+ tiles, turns west onto y=21, runs to x~85, turns north onto x=71
              and runs to y=-54. Generated by bridge/factorio/rails.py from the game's rail
              geometry. A single track; one train, so no signals.
    patch     south-bound stop on the west side at the rail at y=69; the train's front
              locomotive stands at y 63..69 and its wagon at y 56..62, both over coal.
              Four electric drills output straight into the wagon (two each side) and one
              drill feeds the front locomotive's fuel.
    hub       north-bound stop on the east side near y=-42, unloading inserters on the west
              side onto a belt that runs north then west into the coal trunk's top belt.
    train     locomotive (north) + cargo wagon + locomotive (south).

Stages: rails | patch | power | hub | train     Usage: scripts/build_coal_line.py <stage> [--build]
"""
import json
import sys

from _game import tools

from bridge.factorio import rails
from bridge.factorio.planner import batches

START = (145, 72, 0)
LEGS = [("W", 21), ("N", 71, -54)]


def place(entities, build, label):
    counts = {}
    for e in entities:
        counts[e["name"]] = counts.get(e["name"], 0) + 1
    print(label, "plan:", counts)
    for part in batches(entities):
        r = json.loads(tools["place_entities"](json.dumps(part), dry_run=True))
        if r.get("error") or r["failed"]:
            raise SystemExit(f"dry run failed, nothing built: {json.dumps(r)[:1500]}")
    print(label, "dry run clean")
    if not build:
        return
    placed = 0
    for part in batches(entities):
        r = json.loads(tools["place_entities"](json.dumps(part)))
        if r.get("error") or r["failed"]:
            raise SystemExit(f"{label} stopped after {placed}: {json.dumps(r)[:1500]}")
        placed += r["placed"]
    print(label, "placed", placed)


def rails_stage(build):
    pieces, end = rails.route(START, LEGS)
    print("track:", len(pieces), "pieces, ends at", end)
    place([rails.entity(p) for p in pieces], build, "rails")




